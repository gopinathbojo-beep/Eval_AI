@pytest.mark.parametrize("or_line", ["அல்லது", "(அல்லது)", "– அல்லது –", "அல்லது / OR", "[அல்லது]"])
def test_either_or_forms(or_line):
    doc = _choice_paper(f"வினா 2. (அ) கம்பரைப் பற்றி எழுதுக.\n{or_line}\n(ஆ) இளங்கோவைப் பற்றி எழுதுக. (5)")
    got = [(q.display_number, q.normalized_number, q.max_marks, q.choice_group) for q in doc.questions]
